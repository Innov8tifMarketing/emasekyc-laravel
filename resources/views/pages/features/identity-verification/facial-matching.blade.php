    <h2>What is Facial Matching?</h2>
    <p>OkayFace is EMAS eKYC's facial matching component. It compares the live selfie captured during onboarding with the photo on a government-issued ID to confirm both images belong to the same person.</p>
    <p>While OkayDoc confirms a document is authentic and OkayLive verifies the user is real, OkayFace answers: "Is this the right person?" This prevents identity theft when fraudsters possess genuine stolen documents. OkayFace achieves 99.50% accuracy with a 0.000001 false match rate, with processing occurring in real-time for instant verification.</p>

    <h2>What Problems Does It Solve?</h2>
    <h3>Stolen Documents Enable Fraud</h3>
    <p>Fraudsters obtain genuine ID documents through theft, dark web purchases, or social engineering. Even when businesses verify a document is authentic, they cannot confirm the person presenting it is the legitimate owner. This gap allows criminals to open fraudulent accounts and commit financial crimes.</p>

    <h3>Manual Photo Comparison Is Unreliable</h3>
    <p>Training staff to compare selfies with ID photos creates bottlenecks and introduces human error. People vary in their ability to recognize faces, especially across different ethnicities or when photos are taken years apart. Manual verification lacks consistency — the same comparison may yield different results depending on who performs the review.</p>

    <h3>Security Must Balance with User Experience</h3>
    <p>Traditional verification methods require customers to visit physical branches or wait days for manual review, causing application abandonment rates as high as 30%. Companies need instant verification that is both accurate and seamless for legitimate users.</p>

    <h3>Regulatory Compliance Requires Documentation</h3>
    <p>Financial institutions, telecommunications companies, and other regulated industries must demonstrate they have verified customer identities according to KYC and AML requirements. Manual processes create audit challenges and inconsistent documentation.</p>

    <h2>How Businesses Use It</h2>
    <h3>Financial Services and Digital Banking</h3>
    <p>Banks and fintech companies integrate OkayFace into mobile apps to verify customer identities during account opening. After a customer uploads their ID document and captures a selfie, OkayFace instantly confirms the match, enabling same-day account activation. This eliminates branch visits and allows digital banks to onboard customers 24/7 while maintaining regulatory compliance.</p>

    <h3>Cryptocurrency Exchanges</h3>
    <p>Crypto platforms use OkayFace to meet KYC regulations while processing thousands of verification requests daily. When users register accounts or increase transaction limits, OkayFace verifies the person matches their submitted identification. This prevents bad actors from using stolen documents to create accounts for money laundering.</p>

    <h3>Telecommunications and SIM Registration</h3>
    <p>Mobile network operators leverage OkayFace at retail locations and online channels to verify customer identities during SIM card registration. Government regulations in many ASEAN countries mandate carriers confirm user identities before activating mobile services. OkayFace enables instant verification at point of sale while preventing SIM swap fraud.</p>

    <h3>E-Commerce Platforms</h3>
    <p>Online marketplaces implement OkayFace to verify seller identities before granting merchant accounts. This reduces fraudulent storefronts, protects buyers from scams, and builds platform trust. High-value transaction platforms also use OkayFace during checkout to prevent account takeover fraud.</p>

